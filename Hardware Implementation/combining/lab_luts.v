// Pipelined fixed-point sRGB (8-bit) -> CIE Lab converter (D65 white point).
// Latency: 7 clocks after start pulse; done pulses for 1 clock.
module rgb_to_lab_fp (
    input  wire              clk,
    input  wire              start,
    input  wire [7:0]        r_in,
    input  wire [7:0]        g_in,
    input  wire [7:0]        b_in,
    output reg  [9:0]        l_out,
    output reg signed [12:0] a_out,
    output reg signed [12:0] b_out,
    output reg               done
);
    localparam [2:0] S_IDLE = 3'd0, S_LIN = 3'd1, S_XYZ = 3'd2,
                     S_FT   = 3'd3, S_DIF = 3'd4, S_MUL = 3'd5, S_OUT = 3'd6;
    reg [2:0] st = S_IDLE;

    reg [7:0] r_q, g_q, b_q;
    wire [11:0] rl, gl, bl;

    srgb_lin_rom rom_r (.clk(clk), .addr(r_q), .dout(rl));
    srgb_lin_rom rom_g (.clk(clk), .addr(g_q), .dout(gl));
    srgb_lin_rom rom_b (.clk(clk), .addr(b_q), .dout(bl));

    reg [21:0] xn_acc, yn_acc, zn_acc;
    wire [9:0] fx, fy, fz;

    lab_f_rom rom_fx (.clk(clk), .addr(xn_acc[21:13]), .dout(fx));
    lab_f_rom rom_fy (.clk(clk), .addr(yn_acc[21:13]), .dout(fy));
    lab_f_rom rom_fz (.clk(clk), .addr(zn_acc[21:13]), .dout(fz));

    reg [17:0] l_mul;
    reg signed [10:0] a_diff, b_diff;
    reg signed [20:0] a_mul, b_mul;

    initial begin
        l_out = 10'd0;
        a_out = 13'sd0;
        b_out = 13'sd0;
        done  = 1'b0;
    end

    always @(posedge clk) begin
        done <= 1'b0;
        case (st)
            S_IDLE: if (start) begin
                r_q <= r_in;
                g_q <= g_in;
                b_q <= b_in;
                st  <= S_LIN;
            end
            S_LIN: st <= S_XYZ;
            S_XYZ: begin
                xn_acc <= (10'd444 * rl) + (10'd385 * gl) + (10'd195 * bl);
                yn_acc <= (10'd218 * rl) + (10'd732 * gl) + (10'd74  * bl);
                zn_acc <= (10'd18  * rl) + (10'd112 * gl) + (10'd894 * bl);
                st     <= S_FT;
            end
            S_FT: st <= S_DIF;
            S_DIF: begin
                l_mul  <= 8'd116 * fy;
                a_diff <= $signed({1'b0, fx}) - $signed({1'b0, fy});
                b_diff <= $signed({1'b0, fy}) - $signed({1'b0, fz});
                st     <= S_MUL;
            end
            S_MUL: begin
                l_out <= l_mul[17:8];
                a_mul <= a_diff * 11'sd500;
                b_mul <= b_diff * 11'sd200;
                st    <= S_OUT;
            end
            S_OUT: begin
                a_out <= a_mul[20:8];
                b_out <= b_mul[20:8];
                done  <= 1'b1;
                st    <= S_IDLE;
            end
            default: st <= S_IDLE;
        endcase
    end
endmodule

// Restoring integer square root (unsigned). NW must be even.
// QW = NW/2 clocks after start, done pulses for 1 clock with floor(sqrt(num)).
module sqrt_seq #(
    parameter integer NW = 24
)(
    input  wire            clk,
    input  wire            start,
    input  wire [NW-1:0]   num,
    output reg  [NW/2-1:0] root,
    output reg             done
);
    localparam integer QW = NW / 2;

    reg [NW-1:0] rad;
    reg [QW:0]   rem;
    reg [QW+2:0] rem_next;
    reg [QW+2:0] trial_sub;
    reg [5:0]    cnt;
    reg          running = 1'b0;

    initial begin
        root = 0;
        done = 1'b0;
    end

    always @(posedge clk) begin
        done <= 1'b0;
        if (start) begin
            rad     <= num;
            rem     <= 0;
            root    <= 0;
            cnt     <= QW;
            running <= 1'b1;
        end else if (running) begin
            rem_next  = {rem, rad[NW-1:NW-2]};
            trial_sub = {1'b0, root, 2'b01};
            if (rem_next >= trial_sub) begin
                rem  <= rem_next - trial_sub;
                root <= {root[QW-2:0], 1'b1};
            end else begin
                rem  <= rem_next;
                root <= {root[QW-2:0], 1'b0};
            end
            rad <= {rad[NW-3:0], 2'b00};
            cnt <= cnt - 1'b1;
            if (cnt == 6'd1) begin
                running <= 1'b0;
                done    <= 1'b1;
            end
        end
    end
endmodule
